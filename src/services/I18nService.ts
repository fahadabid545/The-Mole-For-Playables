class I18nImpl {
  private lang: Lang = 'en';
  init(l: Lang | undefined): void { if (l && DICT[l]) this.lang = l; }
  setLang(l: Lang): void { this.lang = l; }
  getLang(): Lang { return this.lang; }
  isRTL(): boolean { return LANGS.find(x => x.code === this.lang)?.rtl ?? false; }
  t(key: string, vars: Record<string, string | number> = {}): string {
    const s = DICT[this.lang][key] ?? DICT.en[key] ?? key;
    return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
  }
}

export const I18n = new I18nImpl();
